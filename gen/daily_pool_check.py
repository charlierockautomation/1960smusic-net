# -*- coding: utf-8 -*-
"""Daily Guessing Game pool gate: decides which radio-eligible songs are
safe to use for the "guess the year" game and why any others are not.

Excludes (writes data/daily-excluded-ids.json + daily-pool-report.md):
  - missing/invalid accepted year (year or year_alt outside 1960-1969)
  - no on-record status in gen/yt_status_cache.json, embeddable:false, or
    made_for_kids:true (fetched fresh here via yt_video_status.fetch_status,
    part=status,snippet in the same call, so this also captures video
    titles for the next check at no extra quota cost)
  - video title contains a bare 19\\d{2} token (reveals the answer)

daily-app.js filters its pool against data/daily-excluded-ids.json AND
data/daily-manual-exclude.json (Charlie's hand-picked ids from eyeballing
docs/daily-thumbnail-review.html, generated by gen/daily_thumbnail_review.py).

Usage: YOUTUBE_API_KEY=xxx python3 gen/daily_pool_check.py
"""
import json, os, re, sys, glob, datetime

from yt_video_status import fetch_status, record, load_cache as load_status_cache, \
    save_cache as save_status_cache, QUOTA_COST_PER_CALL

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DATA = os.path.join(ROOT, "data")
EXCLUDED_JSON = os.path.join(DATA, "daily-excluded-ids.json")
REPORT_MD = os.path.join(ROOT, "daily-pool-report.md")
YEAR_RE = re.compile(r"\b(19\d{2})\b")

SOURCING_NOTE = (
    "`year` in data/radio-eligible-*.json is hand-curated content (same "
    "process as gen/songs_data.py), asserted as the song's original release "
    "year at the time each entry was added. There is no per-field citation "
    "stored per song -- no source URL or discography reference is recorded "
    "per entry. A mechanical cross-check against data/songs.json's `year` "
    "for every overlapping youtube_id found zero mismatches (internal "
    "consistency, not independent verification). A full per-song audit "
    "against an external discography for all pool entries was not done in "
    "this pass -- flag if you want that as a follow-up."
)


def load_pool():
    out = []
    for path in glob.glob(os.path.join(DATA, "radio-eligible-*.json")):
        out.extend(json.load(open(path)))
    return out


def accepted_years(song):
    years = [song.get("year")]
    if song.get("year_alt") is not None:
        years.append(song["year_alt"])
    return [y for y in years if y is not None]


def main():
    api_key = os.environ.get("YOUTUBE_API_KEY")
    if not api_key:
        sys.exit("Set YOUTUBE_API_KEY env var first.")

    pool = load_pool()
    ids = [s["youtube_id"] for s in pool]
    print("Checking %d pool ids (status + snippet)..." % len(set(ids)))
    status, calls = fetch_status(ids, api_key, include_snippet=True)
    save_status_cache(record(load_status_cache(), status))
    print("%d API call(s), %d quota unit(s)." % (calls, calls * QUOTA_COST_PER_CALL))

    excluded = {}
    dual_year = []
    for s in pool:
        vid = s["youtube_id"]
        years = accepted_years(s)
        bad_years = [y for y in years if not (1960 <= y <= 1969)]
        if not years or bad_years:
            excluded[vid] = "invalid_year: accepted years %s" % (years or "none")
            continue

        st = status.get(vid)
        if not st:
            excluded[vid] = "no_status: not found by videos.list (deleted/private/bad id)"
            continue
        if st["made_for_kids"]:
            excluded[vid] = "made_for_kids: true"
            continue
        if not st["embeddable"]:
            excluded[vid] = "not_embeddable"
            continue

        title = st.get("title") or ""
        m = YEAR_RE.search(title)
        if m:
            excluded[vid] = 'title_exposes_year: "%s" contains %s' % (title, m.group(1))
            continue

        if len(years) > 1:
            dual_year.append((s, years))

    json.dump(excluded, open(EXCLUDED_JSON, "w"), indent=1, sort_keys=True)

    kept = len(pool) - len(excluded)
    lines = ["# Daily Guessing Game -- Pool Report -- %s\n" % datetime.date.today().isoformat(),
             "%d pool entries checked, %d kept, %d excluded.\n" % (len(pool), kept, len(excluded)),
             "## 1. Dual-year songs\n"]
    if dual_year:
        lines += ["| Title | Artist | Years | Source |", "|---|---|---|---|"]
        for s, years in dual_year:
            lines.append("| %s | %s | %s | %s |" % (
                s["title"], s["artist"], " / ".join(str(y) for y in years), s.get("year_alt_source") or ""))
    else:
        lines.append("None on record.\n")

    lines.append("\n## 2. Excluded songs\n")
    if excluded:
        by_reason = {}
        for s in pool:
            if s["youtube_id"] in excluded:
                by_reason.setdefault(excluded[s["youtube_id"]].split(":")[0], []).append((s, excluded[s["youtube_id"]]))
        for reason in sorted(by_reason):
            lines.append("\n### %s (%d)\n" % (reason, len(by_reason[reason])))
            lines += ["| Title | Artist | YouTube ID | Detail |", "|---|---|---|---|"]
            for s, detail in by_reason[reason]:
                lines.append("| %s | %s | %s | %s |" % (s["title"], s["artist"], s["youtube_id"], detail))
    else:
        lines.append("None.\n")

    lines.append("\n## 3. How `year` is sourced\n\n" + SOURCING_NOTE + "\n")
    open(REPORT_MD, "w").write("\n".join(lines) + "\n")

    print("Kept: %d, excluded: %d, dual-year: %d" % (kept, len(excluded), len(dual_year)))
    print("Report:", REPORT_MD)
    print("Excluded ids:", EXCLUDED_JSON)


if __name__ == "__main__":
    main()
